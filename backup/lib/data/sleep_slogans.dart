  static String getRandomSlogan() {
    final random = Random();
    return slogans[random.nextInt(slogans.length)];
  }
  
  // 获取指定类别的随机slogan
  static String getRandomSloganByCategory(String category) {
    final random = Random();
    List<String> categoryList;
    
    switch (category) {
      case 'tips':
        categoryList = sleepTips;
        break;
      case 'science':
        categoryList = sleepScience;
        break;
      case 'facts':
        categoryList = sleepFacts;
        break;
      case 'quotes':
        categoryList = sleepQuotes;
        break;
      case 'psychology':
        categoryList = sleepPsychology;
        break;
      default:
        categoryList = baseSlogans;
    }
    
    return categoryList[random.nextInt(categoryList.length)];
  }
