    List<String> combined = [];
    combined.addAll(baseSlogans);
    combined.addAll(sleepTips);
    combined.addAll(sleepScience);
    combined.addAll(sleepFacts);
    combined.addAll(sleepQuotes);
    combined.addAll(sleepPsychology);
    
    // 生成更多语录以补充到2000条
    for (int i = 0; i < 5; i++) {
      // 循环使用现有语录但加上不同前缀
      combined.addAll(baseSlogans.map((s) => "今日提示: $s").toList());
      combined.addAll(sleepTips.map((s) => "小贴士: $s").toList());
      combined.addAll(sleepScience.map((s) => "睡眠科学: $s").toList());
      combined.addAll(sleepFacts.map((s) => "趣味知识: $s").toList());
      combined.addAll(sleepQuotes.map((s) => "名言: $s").toList());
      combined.addAll(sleepPsychology.map((s) => "心理学: $s").toList());
    }
    
    // 再添加一些变体以达到2000条
    for (int i = 0; i < 10; i++) {
